import fs from 'fs'
import path from 'path'

const keys = [
  'VITE_FIREBASE_API_KEY',
  'VITE_FIREBASE_AUTH_DOMAIN',
  'VITE_FIREBASE_PROJECT_ID',
  'VITE_FIREBASE_STORAGE_BUCKET',
  'VITE_FIREBASE_MESSAGING_SENDER_ID',
  'VITE_FIREBASE_APP_ID',
  'VITE_FIREBASE_MEASUREMENT_ID',
]

const values = {}
for (const k of keys) {
  values[k] = process.env[k] || ''
}

const out = `// Generated by scripts/inject-firebase-config.js from environment variables
self.firebaseConfig = {
  apiKey: ${JSON.stringify(values.VITE_FIREBASE_API_KEY)},
  authDomain: ${JSON.stringify(values.VITE_FIREBASE_AUTH_DOMAIN)},
  projectId: ${JSON.stringify(values.VITE_FIREBASE_PROJECT_ID)},
  storageBucket: ${JSON.stringify(values.VITE_FIREBASE_STORAGE_BUCKET)},
  messagingSenderId: ${JSON.stringify(values.VITE_FIREBASE_MESSAGING_SENDER_ID)},
  appId: ${JSON.stringify(values.VITE_FIREBASE_APP_ID)},
  measurementId: ${JSON.stringify(values.VITE_FIREBASE_MEASUREMENT_ID || undefined)}
};
self.vapidPublicKey = ${JSON.stringify(process.env.VITE_VAPID_PUBLIC_KEY || '')};
`

const publicDir = path.resolve(process.cwd(), 'public')
if (!fs.existsSync(publicDir)) fs.mkdirSync(publicDir)
fs.writeFileSync(path.join(publicDir, 'firebase-config.js'), out)
console.log('Generated public/firebase-config.js')
